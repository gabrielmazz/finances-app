const { chromium } = require('playwright');
const { initializeApp, deleteApp } = require('firebase/app');
const { getAuth, connectAuthEmulator, createUserWithEmailAndPassword } = require('firebase/auth');
const { getFirestore, connectFirestoreEmulator, deleteDoc, doc, getDoc, setDoc, serverTimestamp } = require('firebase/firestore');
const { initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

(async () => {
	const app = initializeApp({ apiKey: 'demo-api-key', projectId: 'demo-lumus-foundation' }, `reference-ui-${Date.now()}`);
	const auth = getAuth(app), db = getFirestore(app);
	connectAuthEmulator(auth, 'http://127.0.0.1:9098', { disableWarnings: true });
	connectFirestoreEmulator(db, '127.0.0.1', 8089);
	const email = `reference-ui-${randomUUID()}@lumus.test`, password = 'Lumus-local-2026!';
	const { user } = await createUserWithEmailAndPassword(auth, email, password);
	await setDoc(doc(db, 'users', user.uid), { name: 'Pessoa Teste', email, adminUser: false, createdAt: serverTimestamp() });
	const bankId = 'browserRefBank000001', context = `personal:${user.uid}`;
	const fixture = await initializeTestEnvironment({ projectId: 'demo-lumus-foundation', firestore: { host: '127.0.0.1', port: 8089 } });
	await fixture.withSecurityRulesDisabled(async c => {
		await setDoc(doc(c.firestore(), 'banks', bankId), { personId: user.uid, name: 'Conta antiga', institutionName: 'Banco Teste', bankIconKey: 'outro-banco', accountType: 'checking' });
		await setDoc(doc(c.firestore(), '_bankScopes', bankId), { scopeKind: 'personal', scopeId: user.uid });
	});
	const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH, args: ['--no-sandbox'] });
	try {
		const page = await browser.newPage({ viewport: { width: Number(process.env.LUMUS_TEST_WIDTH || 1440), height: Number(process.env.LUMUS_TEST_HEIGHT || 1000) } });
		await page.goto('http://127.0.0.1:4173/web');
		await page.getByLabel('Email', { exact: true }).last().fill(email);
		await page.getByLabel('Senha', { exact: true }).last().fill(password);
		await page.getByRole('button', { name: 'Entrar', exact: true }).click();
		await page.waitForURL('**/web/home**');
		await page.getByText('Conta antiga', { exact: true }).filter({ visible: true }).first().waitFor({ timeout: 30000 });
		await page.goto('http://127.0.0.1:4173/web/home?tab=2');
		await page.getByText('Bancos', { exact: true }).first().click();
		await page.getByLabel('Editar banco Conta antiga').first().click();
		await page.getByRole('button', { name: 'Editar', exact: true }).last().click();
		await page.getByRole('button', { name: 'Definir saldo de referência', exact: true }).click();
		await page.getByLabel('Saldo inicial disponível', { exact: true }).last().fill('1.000,00');
		await page.getByRole('button', { name: 'Simular referência', exact: true }).click();
		await page.getByText('Selecione a data do saldo informado pelo banco.', { exact: true }).first().waitFor();
		await page.getByRole('button', { name: 'Selecionar data da referência' }).click();
		await page.getByRole('button', { name: 'Hoje', exact: true }).click();
		await page.getByRole('button', { name: 'Simular referência', exact: true }).click();
		await page.getByText('Selecione o horário do saldo informado pelo banco.', { exact: true }).first().waitFor();
		await page.getByLabel('Horário da referência', { exact: true }).last().fill('0000');
		await page.getByRole('button', { name: 'Simular referência', exact: true }).click();
		await page.getByText('Confirmar saldo de referência?', { exact: true }).waitFor();
		assert.equal((await getDoc(doc(db, 'financialContexts', context, 'bankAccounts', bankId))).exists(), false);
		await page.getByRole('button', { name: 'Cancelar', exact: true }).last().click();
		assert.equal((await getDoc(doc(db, 'financialContexts', context, 'accountOpenings', bankId))).exists(), false);
		await page.getByRole('button', { name: 'Simular referência', exact: true }).click();
		await page.getByText('Confirmar saldo de referência?', { exact: true }).waitFor();
		await page.getByRole('button', { name: 'Confirmar referência', exact: true }).click();
		await page.waitForURL('**/web/home**', { timeout: 30000 });
		const account = await getDoc(doc(db, 'financialContexts', context, 'bankAccounts', bankId));
		const opening = await getDoc(doc(db, 'financialContexts', context, 'accountOpenings', bankId));
		assert.equal(account.data()?.initialBalanceCents, 100000);
		assert.equal(account.data()?.legacyBankId, bankId);
		assert.equal(opening.data()?.type, 'reference');
		assert.equal((await getDoc(doc(db, 'banks', bankId))).data()?.name, 'Conta antiga');
		await page.getByText('Conta antiga', { exact: true }).filter({ visible: true }).first().waitFor({ timeout: 30000 });
		await fixture.withSecurityRulesDisabled(c => deleteDoc(doc(c.firestore(), '_bankScopes', bankId)));
		await page.reload();
		await page.waitForTimeout(2000);
		await page.getByText('Conta antiga', { exact: true }).filter({ visible: true }).first().waitFor({ state: 'hidden', timeout: 30000 });
		await assert.rejects(getDoc(doc(db, 'financialContexts', context, 'bankAccounts', bankId)));
		console.log('Simulação sem escrita e confirmação explícita da referência verificadas na interface.');
		console.log('Após revogação e recarga, a conta protegida não aparece e a leitura é negada.');
	} finally { await browser.close(); await fixture.cleanup(); await deleteApp(app); }
})().catch(error => { console.error(error); process.exitCode = 1; });
